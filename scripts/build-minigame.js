#!/usr/bin/env node
/**
 * Mini Game Build Script
 * Builds for WeChat and Douyin mini game platforms
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { execSync } from 'child_process';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, '..');

const platforms = {
  wechat: {
    name: 'WeChat Mini Game',
    adapter: 'WechatAdapter',
    adapterImport: '@ksgames26/platform-wechat',
    globalVar: 'wx',
  },
  douyin: {
    name: 'Douyin Mini Game',
    adapter: 'DouyinAdapter',
    adapterImport: '@ksgames26/platform-douyin',
    globalVar: 'tt',
  },
};

function showUsage() {
  console.log(`
Usage: node build-minigame.js <platform> [app-path]

Platforms:
  wechat    Build for WeChat Mini Game
  douyin    Build for Douyin Mini Game

Options:
  app-path  Path to app directory (default: apps/demo)

Examples:
  node scripts/build-minigame.js wechat
  node scripts/build-minigame.js wechat apps/my-game
  node scripts/build-minigame.js douyin apps/my-game
`);
}

function generateEntryFile(platform, appSrcDir, outputDir) {
  const config = platforms[platform];

  const entryContent = `/**
 * ${config.name} Entry
 * Auto-generated by build-minigame.js
 */
import 'pixi.js/unsafe-eval'; // Polyfill for unsafe eval in mini game platform
import { inject } from '${config.adapterImport}';
inject(); // Manually inject adapter environment

import { GameApplication } from '@ksgames26/core';
import { ${config.adapter} } from '${config.adapterImport}';
import { initGame } from './game-init';

async function main() {
  const adapter = new ${config.adapter}();

  const game = new GameApplication();
  await game.init({
    platformAdapter: adapter,
    canvas: adapter.createCanvas(),
    debug: false,
  });

  // Initialize game with platform adapter
  await initGame(game, adapter);
}

main().catch(console.error);
`;

  fs.writeFileSync(path.join(outputDir, 'main.ts'), entryContent);
  console.log(`✓ Generated entry file: ${path.join(outputDir, 'main.ts')}`);
}

function generateGameConfig(platform, outputDir) {
  const templatePath = path.join(
    __dirname,
    'templates',
    `${platform}-game.json.template`
  );

  if (fs.existsSync(templatePath)) {
    const content = fs.readFileSync(templatePath, 'utf-8');
    fs.writeFileSync(path.join(outputDir, 'game.json'), content);
    console.log(`✓ Generated game.json`);
  }
}

function generateIndexHTML(platform, outputDir) {
  const htmlContent = `<!DOCTYPE html>
<html>
<head>
  <meta charset="UTF-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1.0, maximum-scale=1.0, user-scalable=no" />
  <title>Mini Game</title>
  <style>
    * { margin: 0; padding: 0; }
    html, body { width: 100%; height: 100%; overflow: hidden; }
    canvas { display: block; }
  </style>
</head>
<body>
  <script type="module" src="./main.ts"></script>
</body>
</html>
`;
  fs.writeFileSync(path.join(outputDir, 'index.html'), htmlContent);
}

function copyUserGameFiles(appSrcDir, outputDir) {
  const gameInitPath = path.join(appSrcDir, 'game-init.ts');

  if (fs.existsSync(gameInitPath)) {
    fs.copyFileSync(gameInitPath, path.join(outputDir, 'game-init.ts'));
    console.log(`✓ Copied game-init.ts`);
  } else {
    // Create default game-init.ts
    const defaultInit = `/**
 * Game Initialization
 * This file should export your game initialization logic
 */
import type { GameApplication } from '@ksgames26/core';
import type { PlatformAdapter } from '@ksgames26/core';

export async function initGame(game: GameApplication, adapter: PlatformAdapter): Promise<void> {
  // Your game initialization code here
  // This is called after the framework is initialized

  console.log('[Game] Initializing...');

  // Example: Add a sprite
  // const sprite = game.factory.createSprite('path/to/texture');
  // game.pixiApp.stage.addChild(sprite);
}
`;
    fs.writeFileSync(path.join(outputDir, 'game-init.ts'), defaultInit);
    console.log(`✓ Created default game-init.ts`);
  }
}

function buildPlatform(platform, appPath) {
  const config = platforms[platform];
  if (!config) {
    console.error(`Unknown platform: ${platform}`);
    console.log(`Supported platforms: ${Object.keys(platforms).join(', ')}`);
    process.exit(1);
  }

  console.log(`\n🎮 Building for ${config.name}...\n`);

  const appDir = path.resolve(rootDir, appPath);
  const appSrcDir = path.join(appDir, 'src');
  const outputDir = path.join(appDir, `dist-${platform}`);

  // Validate app directory
  if (!fs.existsSync(appSrcDir)) {
    console.error(`App source directory not found: ${appSrcDir}`);
    console.log('Make sure your app has a src/ directory with main.ts');
    process.exit(1);
  }

  // Clean and create output directory
  if (fs.existsSync(outputDir)) {
    fs.rmSync(outputDir, { recursive: true });
  }
  fs.mkdirSync(outputDir, { recursive: true });

  // Generate files
  generateEntryFile(platform, appSrcDir, outputDir);
  generateGameConfig(platform, outputDir);
  generateIndexHTML(platform, outputDir);
  copyUserGameFiles(appSrcDir, outputDir);

  console.log(`\n✅ ${config.name} build files generated!`);
  console.log(`\nOutput directory: ${outputDir}`);
  console.log(`\nNext steps:`);
  console.log(`  1. cd ${outputDir}`);
  console.log(`  2. Implement your game logic in game-init.ts`);
  console.log(`  3. Build with Vite: vite build`);
  console.log(`  4. Open with ${platform} developer tools`);
}

// Main
const platform = process.argv[2];
const appPath = process.argv[3] || 'apps/demo';

if (!platform) {
  showUsage();
  process.exit(1);
}

buildPlatform(platform, appPath);
