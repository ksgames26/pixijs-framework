/**
 * Vite Plugin for Mini Game Platforms
 * Automatically handles platform-specific builds
 */

import fs from 'fs';
import path from 'path';

const PLATFORM_CONFIGS = {
  wechat: {
    name: 'WeChat Mini Game',
    adapter: 'WechatAdapter',
    adapterPackage: '@ksgames26/platform-wechat',
    globalVar: 'wx',
    gameJson: {
      deviceOrientation: 'portrait',
      showStatusBar: false,
      networkTimeout: {
        request: 5000,
        connectSocket: 5000,
        uploadFile: 5000,
        downloadFile: 5000,
      },
    },
  },
  douyin: {
    name: 'Douyin Mini Game',
    adapter: 'DouyinAdapter',
    adapterPackage: '@ksgames26/platform-douyin',
    globalVar: 'tt',
    gameJson: {
      deviceOrientation: 'portrait',
      showStatusBar: false,
      networkTimeout: {
        request: 5000,
        connectSocket: 5000,
        uploadFile: 5000,
        downloadFile: 5000,
      },
    },
  },
};

/**
 * Create a virtual entry module for mini game platforms
 */
function createVirtualEntry(platform, gameInitPath) {
  const config = PLATFORM_CONFIGS[platform];

  return `
/**
 * ${config.name} Entry
 * Auto-generated by vite-plugin-minigame
 */
import { GameApplication } from '@ksgames26/core';
import { ${config.adapter} } from '${config.adapterPackage}';
import { initGame } from '${gameInitPath}';

async function main() {
  const adapter = new ${config.adapter}();

  const game = new GameApplication();
  await game.init({
    platformAdapter: adapter,
    debug: false,
  });

  // Initialize user game
  await initGame(game, adapter);

  console.log('[${config.name}] Game initialized');
}

main().catch(console.error);
`;
}

/**
 * Vite plugin for mini game platform builds
 * @param {Object} options
 * @param {string} options.platform - 'wechat' | 'douyin'
 * @param {string} options.gameInitPath - Path to game-init module (relative to project root)
 */
export function minigamePlugin(options = {}) {
  const { platform = 'wechat', gameInitPath = './src/game-init' } = options;
  const config = PLATFORM_CONFIGS[platform];

  if (!config) {
    throw new Error(`Unknown platform: ${platform}. Supported: wechat, douyin`);
  }

  const virtualModuleId = 'virtual:minigame-entry';
  const resolvedVirtualModuleId = '\0' + virtualModuleId;

  return {
    name: 'vite-plugin-minigame',

    config(config, { command }) {
      if (command === 'build') {
        return {
          build: {
            target: 'es2015',
            rollupOptions: {
              output: {
                format: 'cjs',
                entryFileNames: 'game.js',
                chunkFileNames: '[name].js',
                assetFileNames: '[name].[ext]',
              },
            },
          },
          define: {
            'typeof window': '"undefined"',
            'typeof document': '"undefined"',
          },
        };
      }
    },

    resolveId(id) {
      if (id === virtualModuleId) {
        return resolvedVirtualModuleId;
      }
    },

    load(id) {
      if (id === resolvedVirtualModuleId) {
        return createVirtualEntry(platform, gameInitPath);
      }
    },

    generateBundle(options, bundle) {
      // Generate game.json for the platform
      this.emitFile({
        type: 'asset',
        fileName: 'game.json',
        source: JSON.stringify(config.gameJson, null, 2),
      });

      // Generate project.config.json for WeChat
      if (platform === 'wechat') {
        this.emitFile({
          type: 'asset',
          fileName: 'project.config.json',
          source: JSON.stringify(
            {
              description: 'WeChat Mini Game',
              packOptions: { ignore: [] },
              setting: {
                bundle: false,
                es6: true,
                enhance: false,
                postcss: false,
                minified: true,
                newFeature: false,
                bigPackageSizeSupport: true,
              },
              compileType: 'game',
              libVersion: 'latest',
              appid: 'touristappid',
              projectname: 'pixi-game',
              condition: {},
            },
            null,
            2
          ),
        });
      }
    },
  };
}

export default minigamePlugin;
